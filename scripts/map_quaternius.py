"""Create the explicit runtime dependency list; unused library models stay out of exports."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SELECT={
 'tree':('nature','MapleTree_1'), 'birch':('nature','BirchTree_1'),
 'brush':('nature','Bush_Small'), 'grass':('nature','Grass_Small'),
 'rock':('rts','Resource_Rock_1'), 'ore':('rts','Resource_Gold_1'),
 'wall':('village','Wall_Plaster_Straight'), 'window':('village','Wall_Plaster_Window_Wide_Flat'),
 'door':('village','Door_1_Flat'), 'roof':('village','Roof_Modular_RoundTiles'),
 'palisade':('village','Prop_WoodenFence_Single'), 'cart':('village','Prop_Wagon'),
 'floor':('village','Floor_WoodDark'), 'barricade':('props','Crate_Wooden'),
 'stall':('props','Stall_Empty'), 'workbench':('props','Workbench'),
 'dummy':('props','Dummy'), 'loot':('props','Bag'), 'chest':('props','Chest_Wood'),
 'torch':('props','Torch_Metal'), 'banner':('props','Banner_1'),
 'bed':('props','Bed_Twin1'), 'anvil':('props','Anvil'), 'barrel':('props','Barrel'),
 'tent':('camp','Tent'), 'campfire':('camp','Bonfire'), 'bandages':('camp','Bandages'),
 'crop':('crops','Wheat_Crop'), 'food':('items','ChickenLeg'),
 'medicine':('camp','Bandages'), 'tools':('props','Pickaxe_Bronze'), 'currency':('props','Coin_Pile'),
 'dagger':('weapons','Dagger'), 'sword':('weapons','Sword'), 'axe':('weapons','Axe'),
 'spear':('weapons','Spear'), 'greatsword':('weapons','Claymore'), 'bow':('weapons','Bow_Wooden'),
 'javelin':('weapons','Spear'), 'arrows':('weapons','Arrow'), 'shield':('weapons','Shield_Round'),
 'helmet':('helmets','Helmet1'), 'plate':('items','Armor_Metal'), 'mail':('items','Armor_Metal2'),
 'leather':('items','Armor_Leather'), 'backpack':('items','Backpack'),
 'horse':('animals','Horse'), 'donkey':('animals','Donkey'), 'cow':('animals','Cow'),
 'soldier':('characters','Warrior'), 'hunter':('characters','Ranger'),
 'physician':('characters','Cleric'), 'smith':('characters','Monk'),
 'knight':('characters','Warrior'), 'farmer':('characters','Monk'), 'rogue':('characters','Rogue'),
 'market':('rts','Market_FirstAge_Level1'), 'farm':('rts','Farm_FirstAge_Level1'),
 'mine':('rts','Mine'), 'garrison':('rts','Barracks_FirstAge_Level1'),
 'training':('rts','Archery_FirstAge_Level1'), 'workshop':('props','Workbench'),
 'camp':('camp','Tent'),
}
RUNTIME=set('tree brush rock ore wall window door roof palisade cart floor barricade stall workbench dummy loot torch crop tent soldier hunter physician smith knight farmer rogue dagger sword axe spear greatsword bow javelin shield helmet'.split())
def main():
 manifest=json.loads((ROOT/'assets/quaternius/manifest.json').read_text(encoding='utf-8'))
 models={(r['category'],r['name']):r for r in manifest['models']}
 lines=['# Generated by scripts/map_quaternius.py. Explicit dependencies keep exports small.','extends RefCounted','const MODELS={']
 thumbnail_lines=lines.copy()
 selected={}
 for key, source in SELECT.items():
  row=models[source]
  entry=' '+json.dumps(key)+':preload('+json.dumps(row['path'])+'),'
  thumbnail_lines.append(entry)
  if key in RUNTIME:lines.append(entry)
  selected[key]=row['path']
 lines.append('}\n')
 thumbnail_lines.append('}\n')
 (ROOT/'ui/asset_catalog.gd').write_text('\n'.join(lines),encoding='utf-8')
 (ROOT/'scripts/thumbnail_catalog.gd').write_text('\n'.join(thumbnail_lines),encoding='utf-8')
 active={k:v for k,v in selected.items() if k in RUNTIME}
 (ROOT/'assets/quaternius/runtime-map.json').write_text(json.dumps({'models':active,'icon_sources':selected},indent=2)+'\n',encoding='utf-8')
 icons=ROOT/'ui/asset_icons.gd'
 source=icons.read_text(encoding='utf-8')
 import re
 entries=[' '+json.dumps(key)+':preload("res://assets/ui/icons/'+key+'.png"),' for key in selected if (ROOT/'assets/ui/icons'/ (key+'.png')).exists()]
 source=re.sub(r'const TEXTURES=\{[^}]*\}', 'const TEXTURES={\n'+'\n'.join(entries)+'\n}',source)
 icons.write_text(source,encoding='utf-8')
 # Godot's selected-resource exporter does not discover every GDScript preload.
 # Include the small runtime explicitly; imported scene/material dependencies
 # are then followed by the exporter. Library-only models are not selected.
 files=['res://main.tscn','res://icon.svg']
 files+=['res://'+p.relative_to(ROOT).as_posix() for folder in ['sim','ui'] for p in sorted((ROOT/folder).glob('*.gd'))]
 files+=sorted(set(active.values()))
 files+=['res://assets/ui/icons/'+key+'.png' for key in selected if (ROOT/'assets/ui/icons'/(key+'.png')).exists()]
 presets=ROOT/'export_presets.cfg'
 config=presets.read_text(encoding='utf-8')
 config=re.sub(r'export_files=PackedStringArray\([^\n]*\)',lambda _: 'export_files=PackedStringArray('+', '.join(json.dumps(p) for p in files)+')',config)
 presets.write_text(config,encoding='utf-8')
 print('Runtime model mappings:',len(active),'unique runtime models:',len(set(active.values())),'thumbnail mappings:',len(selected),'unique thumbnail source models:',len(set(selected.values())))
if __name__=='__main__':main()
